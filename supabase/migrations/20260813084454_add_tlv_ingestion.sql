create or replace function private.delete_expired_positions(batch_size integer default 50000)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  deleted_positions integer;
  deleted_observations integer;
begin
  delete from public.positions
  where id in (
    select id
    from public.positions
    where recorded_at < now() - interval '7 days'
    order by recorded_at
    limit greatest(1, least(batch_size, 50000))
  );
  get diagnostics deleted_positions = row_count;

  delete from public.observations
  where id in (
    select id
    from public.observations
    where recorded_at < now() - interval '7 days'
    order by recorded_at
    limit greatest(1, least(batch_size, 50000))
  );
  get diagnostics deleted_observations = row_count;

  return deleted_positions + deleted_observations;
end;
$$;

revoke execute on function private.delete_expired_positions(integer)
  from public, anon, authenticated;

