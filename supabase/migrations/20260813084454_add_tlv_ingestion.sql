create or replace function public.ingest_tlv_observation(
  p_protocol_version smallint,
  p_device_guid16 integer,
  p_msg_seq_id integer,
  p_time_unix bigint,
  p_status smallint,
  p_power_profile smallint,
  p_flags smallint,
  p_tx_reason smallint,
  p_gnss_valid boolean,
  p_latitude double precision,
  p_longitude double precision,
  p_batt_mv integer,
  p_acc_m integer,
  p_fix_age_s integer,
  p_sat_count integer,
  p_tlv_data jsonb,
  p_payload_hash text,
  p_payload_b64 text,
  p_hmac_body_b64 text,
  p_hmac_tag_hex text,
  p_ingest_path text,
  p_link_type text,
  p_gateway_guid16 integer,
  p_gateway_rx_time_unix bigint,
  p_link_rssi_dbm double precision,
  p_link_snr_db double precision,
  p_cell_rsrp_dbm double precision,
  p_cell_rsrq_db double precision,
  p_cell_sinr_db double precision
)
returns table (
  accepted boolean,
  duplicate boolean,
  observation_id bigint,
  position_id bigint,
  received_at timestamptz,
  error_code text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_household_id uuid;
  v_observation_id bigint;
  v_position_id bigint;
  v_request_received_at timestamptz := clock_timestamp();
  v_observation_received_at timestamptz;
  v_duplicate boolean := false;
  v_route_key text;
begin
  select device.household_id
  into v_household_id
  from public.devices as device
  where device.device_id = p_device_guid16
    and device.enabled = true;

  if v_household_id is null then
    return query select false, false, null::bigint, null::bigint, v_request_received_at, 'unauthorized_device'::text;
    return;
  end if;

  if not exists (
    select 1
    from public.device_hmac_keys as device_key
    join vault.decrypted_secrets as secret
      on secret.id = device_key.vault_secret_id
    where device_key.device_id = p_device_guid16
      and device_key.enabled = true
      and device_key.valid_from <= v_request_received_at
      and (device_key.valid_until is null or device_key.valid_until > v_request_received_at)
      and substring(
        extensions.hmac(
          decode(p_hmac_body_b64, 'base64'),
          decode(secret.decrypted_secret, 'base64'),
          'sha256'
        )
        from 1 for 8
      ) = decode(p_hmac_tag_hex, 'hex')
  ) then
    return query select false, false, null::bigint, null::bigint, v_request_received_at, 'invalid_authentication'::text;
    return;
  end if;

  if exists (
    select 1
    from public.observations as existing
    where existing.device_guid16 = p_device_guid16
      and existing.msg_seq_id = p_msg_seq_id
      and existing.time_unix = p_time_unix
      and existing.payload_hash <> p_payload_hash
  ) then
    return query select false, false, null::bigint, null::bigint, v_request_received_at, 'message_identity_conflict'::text;
    return;
  end if;

  insert into public.observations (
    device_guid16,
    household_id,
    protocol_version,
    msg_seq_id,
    time_unix,
    recorded_at,
    status,
    power_profile,
    flags,
    tx_reason,
    gnss_valid,
    latitude,
    longitude,
    batt_mv,
    acc_m,
    fix_age_s,
    sat_count,
    tlv_data,
    payload_hash,
    payload_b64,
    received_at
  )
  values (
    p_device_guid16,
    v_household_id,
    p_protocol_version,
    p_msg_seq_id,
    p_time_unix,
    to_timestamp(p_time_unix),
    p_status,
    p_power_profile,
    p_flags,
    p_tx_reason,
    p_gnss_valid,
    p_latitude,
    p_longitude,
    p_batt_mv,
    p_acc_m,
    p_fix_age_s,
    p_sat_count,
    coalesce(p_tlv_data, '{}'::jsonb),
    p_payload_hash,
    p_payload_b64,
    v_request_received_at
  )
  on conflict do nothing
  returning id into v_observation_id;

  if v_observation_id is null then
    select existing.id, existing.received_at
    into v_observation_id, v_observation_received_at
    from public.observations as existing
    where existing.payload_hash = p_payload_hash;
    v_duplicate := true;
  else
    v_observation_received_at := v_request_received_at;
  end if;

  if v_observation_id is null then
    return query select false, false, null::bigint, null::bigint, v_request_received_at, 'message_identity_conflict'::text;
    return;
  end if;

  v_route_key := case
    when p_ingest_path = 'lora_hub'
      then 'lora_hub:' || lpad(to_hex(p_gateway_guid16), 4, '0')
    else 'cellular_direct'
  end;

  insert into public.observation_paths (
    observation_id,
    household_id,
    route_key,
    ingest_path,
    link_type,
    gateway_guid16,
    gateway_rx_time_unix,
    link_rssi_dbm,
    link_snr_db,
    cell_rsrp_dbm,
    cell_rsrq_db,
    cell_sinr_db,
    first_received_at,
    last_received_at,
    receipt_count
  )
  values (
    v_observation_id,
    v_household_id,
    v_route_key,
    p_ingest_path,
    p_link_type,
    p_gateway_guid16,
    p_gateway_rx_time_unix,
    p_link_rssi_dbm,
    p_link_snr_db,
    p_cell_rsrp_dbm,
    p_cell_rsrq_db,
    p_cell_sinr_db,
    v_request_received_at,
    v_request_received_at,
    1
  )
  on conflict (observation_id, route_key) do update
  set
    gateway_rx_time_unix = excluded.gateway_rx_time_unix,
    link_rssi_dbm = excluded.link_rssi_dbm,
    link_snr_db = excluded.link_snr_db,
    cell_rsrp_dbm = excluded.cell_rsrp_dbm,
    cell_rsrq_db = excluded.cell_rsrq_db,
    cell_sinr_db = excluded.cell_sinr_db,
    last_received_at = clock_timestamp(),
    receipt_count = public.observation_paths.receipt_count + 1;

  if p_gnss_valid then
    select position.id into v_position_id
    from public.positions as position
    where position.observation_id = v_observation_id;

    if v_position_id is null and not v_duplicate then
      insert into public.positions (
        device_uid,
        message_id,
        latitude,
        longitude,
        battery,
        source,
        recorded_at,
        received_at,
        schema_version,
        observation_id,
        battery_mv,
        status_code,
        power_profile_code,
        flags,
        tx_reason,
        link_type,
        link_rssi_dbm,
        link_snr_db
      )
      values (
        p_device_guid16,
        p_msg_seq_id,
        p_latitude,
        p_longitude,
        null,
        'tlv',
        to_timestamp(p_time_unix),
        v_observation_received_at,
        p_protocol_version,
        v_observation_id,
        p_batt_mv,
        p_status,
        p_power_profile,
        p_flags,
        p_tx_reason,
        p_link_type,
        p_link_rssi_dbm,
        p_link_snr_db
      )
      on conflict (device_uid, message_id) do update
      set
        latitude = excluded.latitude,
        longitude = excluded.longitude,
        battery = excluded.battery,
        source = excluded.source,
        recorded_at = excluded.recorded_at,
        received_at = excluded.received_at,
        schema_version = excluded.schema_version,
        observation_id = excluded.observation_id,
        battery_mv = excluded.battery_mv,
        status_code = excluded.status_code,
        power_profile_code = excluded.power_profile_code,
        flags = excluded.flags,
        tx_reason = excluded.tx_reason,
        link_type = excluded.link_type,
        link_rssi_dbm = excluded.link_rssi_dbm,
        link_snr_db = excluded.link_snr_db
      where public.positions.recorded_at < excluded.recorded_at
      returning id into v_position_id;
    end if;

    if v_position_id is null and v_duplicate then
      select position.id into v_position_id
      from public.positions as position
      where position.observation_id = v_observation_id;
    end if;
  end if;

  return query select true, v_duplicate, v_observation_id, v_position_id, v_request_received_at, null::text;
end;
$$;

