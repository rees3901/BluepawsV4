-- Add authenticated TLV telemetry while preserving the legacy JSON position
-- contract. Collar HMAC keys live in Vault; only a narrowly granted RPC can
-- use their decrypted values. Valid GNSS observations are projected into the
-- existing positions/current-position/Realtime pipeline.

set lock_timeout = '5s';
set statement_timeout = '120s';

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

-- Cover the existing composite device-appearance foreign key. The production
-- advisor reports it as unindexed before this migration.
create index if not exists device_appearances_device_household_idx
  on public.device_appearances (device_id, household_id);

do $$
begin
  if to_regclass('vault.secrets') is null
    or to_regclass('vault.decrypted_secrets') is null then
    raise exception 'Supabase Vault must be enabled before applying TLV ingestion';
  end if;
end
$$;

